import assert from 'node:assert/strict';
import {updateHistory,RETENTION_MS} from './odds-history.mjs';
const t=Date.parse('2026-11-07T12:00:00Z'),event={id:'event',home:'A',away:'B',startsAt:'2026-11-08T12:00:00Z'};
const api=(at,price,extra={})=>({events:[event],quotes:[{id:'quote',eventId:'event',bookmakerId:'giro',marketId:'ft_1x2',selection:'home',selectionName:'A',decimalOdds:price,observedAt:new Date(at).toISOString(),method:'automatic',freshness:'current',...extra}]});
let history=updateHistory(null,api(t,2),t);assert.equal(history.alerts.length,0);
history=updateHistory(history,api(t,2),t+1000);assert.equal(history.series[0].samples.length,1);
history=updateHistory(history,api(t+1800000,2.6),t+1800000);assert.equal(history.alerts.length,1);assert.equal(Math.round(history.alerts[0].changePercent),30);
history=updateHistory(history,api(t+3600000,1.8),t+3600000);assert.equal(history.alerts[0].direction,'down');
assert.equal(updateHistory(null,api(t,3,{method:'browser_manual'}),t).series.length,0);
assert.equal(updateHistory(null,api(t+1,3),t).series.length,0);
assert.equal(updateHistory(null,api(t,3,{freshness:'historical'}),t).series.length,0);
const expired=updateHistory(history,{events:[],quotes:[]},t+RETENTION_MS+3600001);assert.equal(expired.series.length,0);assert.equal(expired.alerts.length,0);
const restored=updateHistory(JSON.parse(JSON.stringify(history)),{events:[],quotes:[]},t+7200000);assert.equal(restored.series[0].samples.length,3);assert.equal(restored.startedAt,history.startedAt);
assert.throws(()=>updateHistory({schemaVersion:'wrong'},api(t,2),t));
assert.equal(updateHistory(updateHistory(null,api(t,2),t),api(t+1,2.4),t+1).alerts.length,1);
let gradual=updateHistory(null,api(t,2),t);
gradual=updateHistory(gradual,api(t+1,2.2),t+1);
gradual=updateHistory(gradual,api(t+2,2.5),t+2);
assert.equal(gradual.alerts[0].scope,'since_first_in_window');
console.log('History: persistence, retention, deduplication, movement, stale/manual exclusion OK');
